#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const source = resolve(
  root,
  "apps/web/src/features/body-explorer/data/body-regions.v1.json",
);
const target = resolve(
  root,
  "apps/api/internal/service/body_region_ids_generated.go",
);

const ontology = JSON.parse(await readFile(source, "utf8"));
if (ontology.schemaVersion !== 1 || ontology.ontologyVersion !== 1) {
  throw new Error("unsupported BodyRegionOntology version");
}
const ids = ontology.regions.map((region) => region.id);
if (new Set(ids).size !== ids.length) throw new Error("duplicate BodyRegionId");

const entries = ids
  .sort((a, b) => a.localeCompare(b))
  .map((id) => `\t${JSON.stringify(id)}: {},`)
  .join("\n");

const content = `// Code generated by scripts/body-region/generate-go-validator.mjs; DO NOT EDIT.\n// Source of truth: apps/web/src/features/body-explorer/data/body-regions.v1.json\n\npackage service\n\nvar canonicalBodyRegionIDs = map[string]struct{}{\n${entries}\n}\n\n// IsCanonicalBodyRegionID validates a durable BodyRegionId against the generated\n// BodyRegionOntology v1 set. The JSON ontology remains the source of truth.\nfunc IsCanonicalBodyRegionID(id string) bool {\n\t_, ok := canonicalBodyRegionIDs[id]\n\treturn ok\n}\n\n// NewCanonicalBodyRegionIDValidator adapts the generated ontology set to the\n// durable BodyState validation seam.\nfunc NewCanonicalBodyRegionIDValidator() BodyRegionIDValidator {\n\treturn BodyRegionIDValidatorFunc(IsCanonicalBodyRegionID)\n}\n`;

await writeFile(target, content, "utf8");
console.log(`generated ${target} from ${ids.length} canonical regions`);
