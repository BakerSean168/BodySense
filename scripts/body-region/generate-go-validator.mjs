#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const source = resolve(
  root,
  "apps/web/src/features/body-explorer/data/body-regions.v1.json",
);
const target = resolve(
  root,
  "apps/api/internal/service/body_region_ids_generated.go",
);

const ontology = JSON.parse(await readFile(source, "utf8"));
if (ontology.schemaVersion !== 1 || ontology.ontologyVersion !== 1) {
  throw new Error("unsupported BodyRegionOntology version");
}
const ids = ontology.regions.map((region) => region.id);
if (new Set(ids).size !== ids.length) throw new Error("duplicate BodyRegionId");

const normalize = (value) => String(value ?? "").trim().toLowerCase();
const ambiguousAliases = new Set(
  (ontology.ambiguousAliases ?? []).map((item) => normalize(item.alias)),
);
const aliasOwners = new Map();
for (const region of ontology.regions) {
  const values = [
    region.id,
    region.labels?.["zh-CN"],
    region.labels?.en,
    ...(region.aliases ?? []),
  ];
  for (const value of values) {
    const alias = normalize(value);
    if (!alias || ambiguousAliases.has(alias)) continue;
    const owners = aliasOwners.get(alias) ?? new Set();
    owners.add(region.id);
    aliasOwners.set(alias, owners);
  }
}
const uniqueAliases = [...aliasOwners.entries()]
  .filter(([, owners]) => owners.size === 1)
  .map(([alias, owners]) => [alias, [...owners][0]])
  .sort(([a], [b]) => a.localeCompare(b));

const idEntries = ids
  .sort((a, b) => a.localeCompare(b))
  .map((id) => `\t${JSON.stringify(id)}: {},`)
  .join("\n");
const aliasEntries = uniqueAliases
  .map(([alias, id]) => `\t${JSON.stringify(alias)}: ${JSON.stringify(id)},`)
  .join("\n");

const content = `// Code generated by scripts/body-region/generate-go-validator.mjs; DO NOT EDIT.\n// Source of truth: apps/web/src/features/body-explorer/data/body-regions.v1.json\n\npackage service\n\nimport \"strings\"\n\nvar canonicalBodyRegionIDs = map[string]struct{}{\n${idEntries}\n}\n\nvar canonicalBodyRegionAliases = map[string]string{\n${aliasEntries}\n}\n\n// IsCanonicalBodyRegionID validates a durable BodyRegionId against the generated\n// BodyRegionOntology v1 set. The JSON ontology remains the source of truth.\nfunc IsCanonicalBodyRegionID(id string) bool {\n\t_, ok := canonicalBodyRegionIDs[id]\n\treturn ok\n}\n\n// ResolveCanonicalBodyRegionID resolves only ontology aliases that identify one\n// canonical region unambiguously. Ambiguous aliases intentionally return false.\nfunc ResolveCanonicalBodyRegionID(value string) (string, bool) {\n\tid, ok := canonicalBodyRegionAliases[strings.ToLower(strings.TrimSpace(value))]\n\treturn id, ok\n}\n\n// NewCanonicalBodyRegionIDValidator adapts the generated ontology set to the\n// durable BodyState validation seam.\nfunc NewCanonicalBodyRegionIDValidator() BodyRegionIDValidator {\n\treturn BodyRegionIDValidatorFunc(IsCanonicalBodyRegionID)\n}\n`;

await writeFile(target, content, "utf8");
console.log(
  `generated ${target} from ${ids.length} canonical regions and ${uniqueAliases.length} unique aliases`,
);
