#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import YAML from "yaml";

const root = process.cwd();
const inventoryPath = path.join(root, "docs/refactor/vnext/baseline/current-system-inventory.json");
const specPath = path.join(root, "packages/contracts/openapi/bodysense.v1.openapi.yaml");
const policyPath = path.join(root, "contracts/public-route-policy.json");
const jsonOut = path.join(root, "docs/refactor/vnext/phase-02-public-route-coverage.json");
const mdOut = path.join(root, "docs/refactor/vnext/phase-02-public-route-coverage.md");
const mode = process.argv.includes("--check") ? "check" : "write";
const requireComplete = process.argv.includes("--require-complete");
const methods = new Set(["get", "post", "put", "patch", "delete", "options", "head"]);

function readJSON(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
function key(method, routePath) {
  const normalized = routePath
    .split("/")
    .map((segment) =>
      segment.startsWith(":") || /^\{[^}]+\}$/.test(segment) ? ":*" : segment,
    )
    .join("/");
  return `${method.toUpperCase()} ${normalized}`;
}
function policyMap(items) {
  return new Map(items.map((item) => [key(item.method, item.path), item]));
}

const inventory = readJSON(inventoryPath);
const baseline = inventory.publicApi.goRoutes;
const spec = YAML.parse(fs.readFileSync(specPath, "utf8"));
const policy = readJSON(policyPath);
const excluded = policyMap(policy.excludedBaselineRoutes ?? []);
const retired = policyMap(policy.retiredBaselineRoutes ?? []);
const approvedNew = policyMap(policy.approvedNewRoutes ?? []);

const openapi = new Map();
for (const [routePath, pathItem] of Object.entries(spec.paths ?? {})) {
  for (const [method, operation] of Object.entries(pathItem ?? {})) {
    if (!methods.has(method.toLowerCase())) continue;
    const routeKey = key(method, routePath);
    if (openapi.has(routeKey)) throw new Error(`duplicate OpenAPI operation after path normalization: ${routeKey}`);
    openapi.set(routeKey, {
      method: method.toUpperCase(),
      path: routePath,
      operationId: operation?.operationId ?? null,
    });
  }
}

const baselineKeys = new Set(baseline.map((route) => key(route.method, route.path)));
const routes = baseline.map((route) => {
  const routeKey = key(route.method, route.path);
  const operation = openapi.get(routeKey);
  if (operation) {
    return { ...route, status: "OPENAPI", operationId: operation.operationId, openapiPath: operation.path };
  }
  const excludedPolicy = excluded.get(routeKey);
  if (excludedPolicy) return { ...route, status: "EXCLUDED_OPERATIONAL", reason: excludedPolicy.reason };
  const retiredPolicy = retired.get(routeKey);
  if (retiredPolicy) return { ...route, status: "RETIRED", reason: retiredPolicy.reason };
  return { ...route, status: "MISSING" };
});

const unknownOpenAPI = [];
for (const [routeKey, operation] of openapi) {
  if (baselineKeys.has(routeKey)) continue;
  const approved = approvedNew.get(routeKey);
  if (!approved) unknownOpenAPI.push(operation);
}
if (unknownOpenAPI.length) {
  throw new Error(`OpenAPI contains operations absent from the Phase 00 baseline and not approved in policy: ${JSON.stringify(unknownOpenAPI)}`);
}

const count = (status) => routes.filter((route) => route.status === status).length;
const baselineCount = routes.length;
const excludedCount = count("EXCLUDED_OPERATIONAL");
const retiredCount = count("RETIRED");
const eligibleCount = baselineCount - excludedCount - retiredCount;
const documentedCount = count("OPENAPI");
const missingCount = count("MISSING");
const coveragePercent = eligibleCount === 0 ? 100 : Number(((documentedCount / eligibleCount) * 100).toFixed(2));
const report = {
  schemaVersion: 1,
  baselineCommit: inventory.capturedFrom.commit,
  authority: "packages/contracts/openapi/bodysense.v1.openapi.yaml",
  totals: {
    baseline: baselineCount,
    browserFacingEligible: eligibleCount,
    openapi: documentedCount,
    missing: missingCount,
    retired: retiredCount,
    excludedOperational: excludedCount,
    coveragePercent,
  },
  routes,
};
const json = `${JSON.stringify(report, null, 2)}\n`;
const missingLines = routes
  .filter((route) => route.status === "MISSING")
  .map((route) => `- \`${route.method} ${route.path}\``)
  .join("\n");
const md = `# Phase 02 Public REST Coverage\n\n> Generated by \`pnpm contracts:route-coverage\`. Do not hand-edit.\n\n- Phase 00 baseline routes: **${baselineCount}**\n- Browser-facing eligible routes: **${eligibleCount}**\n- OpenAPI-authoritative routes: **${documentedCount}**\n- Missing migration routes: **${missingCount}**\n- Retired routes: **${retiredCount}**\n- Operational exclusions: **${excludedCount}**\n- Coverage: **${coveragePercent}%**\n\n## Missing routes\n\n${missingLines || "None."}\n`;

if (mode === "check") {
  for (const [file, expected] of [[jsonOut, json], [mdOut, md]]) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) {
      console.error(`stale public-route coverage report: ${path.relative(root, file)}`);
      process.exit(1);
    }
  }
} else {
  fs.writeFileSync(jsonOut, json);
  fs.writeFileSync(mdOut, md);
}

console.log(`public REST coverage: ${documentedCount}/${eligibleCount} (${coveragePercent}%), missing=${missingCount}, retired=${retiredCount}, operational=${excludedCount}`);
if (requireComplete && missingCount !== 0) process.exit(1);
